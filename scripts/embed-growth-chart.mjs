import {readFile,writeFile} from 'node:fs/promises';
const root=new URL('../',import.meta.url),prefix='#page-potty-chart';
const html=await readFile(new URL('potty_chart/index.html',root),'utf8');
const start=html.indexOf('    <section class="chart-card"'),end=html.indexOf('    <footer class="promo-foot"');
if(start<0 || end<start) throw Error('Cannot locate the chart document to embed.');
let body=html.slice(start,end).replace(/<!--[\s\S]*?-->/g,'').replace(/[ \t]+$/gm,'').trim();
body=body.replace('Your Chrysalis file</h2>','Chart sync</h2>');
body=body.replace('If you link your chart below, it also saves to your Chrysalis file.','Signing in automatically saves it to your Chrysalis file.');
body=body.replace('<p>Edits, row removals and stars sync automatically while the chart is open.', '<p>Manage your shared account in <a href="#settings">Settings &amp; data</a>. Edits, row removals and stars sync automatically while Little Log is open.');
const block='<!-- BEGIN EMBEDDED POTTY CHART -->\n      <section id="page-potty-chart" class="page" hidden aria-labelledby="potty-page-title">\n        <div class="page-heading"><div><p class="eyebrow">CHRYSALIS // GROWTH RECORD</p><h1 id="potty-page-title" tabindex="-1">POTTY CHART<span>.</span></h1><p class="subtitle">Your rows, gold stars, and weekly progress.</p></div></div>\n'+body+'\n      </section>\n      <!-- END EMBEDDED POTTY CHART -->';
