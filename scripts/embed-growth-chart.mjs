if(!index.includes('<!-- BEGIN EMBEDDED POTTY CHART -->')) throw Error('Missing embedded chart marker.');
await writeFile(new URL('index.html',root),index.replace(/<!-- BEGIN EMBEDDED POTTY CHART -->[\s\S]*?<!-- END EMBEDDED POTTY CHART -->/,()=>block));
function scope(css) { // Walk nested rule blocks so responsive chart rules stay inside the Little Log chart view.
  let output='',pos=0;
  while(pos<css.length) {
    const open=css.indexOf('{',pos); if(open<0) break;
    const selector=css.slice(pos,open).trim(); let depth=1,end=open+1,quote='';
    for(;end<css.length && depth;end++) {
      const ch=css[end];
      if(quote) {if(ch.charCodeAt(0)===92)end++; else if(ch===quote)quote='';}
      else if(ch==='"' || ch==="'")quote=ch;
      else if(ch==='{')depth++;else if(ch==='}')depth--;
    }
    if(depth)throw Error('Unclosed chart CSS rule.');
    const content=css.slice(open+1,end-1);pos=end;
    if(selector.startsWith('@keyframes')) {if(!selector.includes('crt-flicker'))output+=selector+'{'+content+'}\n';continue;}
    if(selector.startsWith('@')) {output+=selector+'{'+scope(content)+'}\n';continue;}
    const selectors=selector.split(',').map(value=>value.trim()).flatMap(value=>{
      if(value===':root')return [prefix];
      if(value.startsWith('html.crt-disabled .star-cell'))return [value.replace(' .star-cell',' '+prefix+' .star-cell')];
      if(/^(html|body)(\b|:)/.test(value))return [];
      return [prefix+' '+value];
    });
    if(selectors.length)output+=selectors.join(', ')+'{'+content+'}\n';
  }
  return output;
}
const css=await readFile(new URL('potty_chart/style.css',root),'utf8');
await writeFile(new URL('potty_chart/embedded.css',root),'/* Generated by scripts/embed-growth-chart.mjs; source styles remain scoped to this view. */\n'+scope(css.replace(/\/\*[\s\S]*?\*\//g,''))+'\n#page-potty-chart { min-width: 0; }\n#page-potty-chart .chart-card { width: 100%; margin: 0; }\n#page-potty-chart .name-line input { width: min(240px, 100%); }\n#page-potty-chart .account-card .action { letter-spacing: .06em; }\n#page-potty-chart .star-cell { margin: 0; }\n#page-potty-chart [hidden] { display: none !important; }\n');
